"""Typed schemas and data models for NEXUS Adaptive Analyst Engine."""

from datetime import UTC, date, datetime
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class SkillDomain(str, Enum):
    """Eight primary analytical skill domains."""
    DISCOVERY = "Data Discovery & Exploration"
    QUALITY = "Data Quality & Governance"
    CUSTOMER_REVENUE = "Customer & Revenue Analytics"
    PREDICTIVE = "Predictive & Statistical Analytics"
    DIAGNOSTIC = "Diagnostic & Root Cause Analytics"
    RETENTION = "Retention & Experimentation"
    COMMERCIAL = "Commercial & Financial Analytics"
    REPORTING = "Reporting & Decision Intelligence"


class SkillMetadata(BaseModel):
    """Complete metadata contract for every registered analyst skill."""
    skill_id: str
    name: str
    description: str
    domain: SkillDomain
    version: str = "1.0.0"
    activation_conditions: List[str] = Field(default_factory=list)
    required_input_data: List[str] = Field(default_factory=list)
    required_data_quality: float = 60.0
    methodology: str
    confidence_methodology: str
    known_limitations: List[str] = Field(default_factory=list)
    evidence_requirements: List[str] = Field(default_factory=list)
    enabled: bool = True
    test_coverage: str = "automated-unit"


class SkillExecutionResult(BaseModel):
    """Deterministic output payload generated by an analyst skill execution."""
    skill_id: str
    skill_name: str
    domain: SkillDomain
    status: str = "SUCCESS"  # SUCCESS, INSUFFICIENT_DATA, FAILED, SKIPPED
    data: Dict[str, Any] = Field(default_factory=dict)
    calculations: List[Dict[str, Any]] = Field(default_factory=list)
    findings: List[str] = Field(default_factory=list)
    confidence_score: float = 0.85
    limitations: List[str] = Field(default_factory=list)
    execution_time_ms: float = 0.0
    evidence: Dict[str, Any] = Field(default_factory=dict)
    error_message: Optional[str] = None


class ExecutionContext(BaseModel):
    """Tenant-scoped execution environment passed to skills during orchestration."""
    business_id: str
    organization_id: Optional[str] = None
    user_id: Optional[str] = None
    date_from: Optional[datetime] = None
    date_to: Optional[datetime] = None
    query: Optional[str] = None
    target_metric: Optional[str] = None
    parameters: Dict[str, Any] = Field(default_factory=dict)
    prior_results: Dict[str, SkillExecutionResult] = Field(default_factory=dict)
