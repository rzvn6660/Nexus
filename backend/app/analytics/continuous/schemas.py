"""Pydantic schemas and enums for Continuous Intelligence (Phase 29)."""

from datetime import datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class FindingSeverity(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class FindingStatus(str, Enum):
    ACTIVE = "ACTIVE"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    DISMISSED = "DISMISSED"
    RESOLVED = "RESOLVED"
    EXPIRED = "EXPIRED"


class ChangeType(str, Enum):
    TREND_SHIFT = "TREND_SHIFT"
    STATISTICAL_ANOMALY = "STATISTICAL_ANOMALY"
    THRESHOLD_BREACH = "THRESHOLD_BREACH"
    VARIANCE_SPIKE = "VARIANCE_SPIKE"


class EvidenceQualityGrade(str, Enum):
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"
    INSUFFICIENT = "INSUFFICIENT"


class ScanTriggerType(str, Enum):
    MANUAL = "MANUAL"
    SCHEDULED = "SCHEDULED"
    INGESTION = "INGESTION"


class FeedbackType(str, Enum):
    HELPFUL = "HELPFUL"
    UNHELPFUL = "UNHELPFUL"
    FALSE_POSITIVE = "FALSE_POSITIVE"
    IGNORED = "IGNORED"


class MetricShiftObservation(BaseModel):
    """Deterministic candidate observation generated by the detection engine."""
    metric_key: str
    entity_type: str = "business"
    entity_id: str = "all"
    entity_name: str | None = None
    change_type: ChangeType
    title: str
    summary: str
    current_value: float
    baseline_value: float
    delta_value: float
    relative_change_pct: float
    unit: str
    period_start: datetime
    period_end: datetime
    baseline_period_start: datetime | None = None
    baseline_period_end: datetime | None = None
    confidence_score: float = Field(ge=0.0, le=1.0, description="Heuristic confidence weight (not calibrated probability)")
    business_impact_score: float = Field(ge=0.0, le=1.0, description="Heuristic monetary or volume impact weight (not probability)")
    urgency_score: float = Field(ge=0.0, le=1.0, description="Heuristic directional operational urgency weight (not probability)")
    severity: FindingSeverity
    evidence_quality: EvidenceQualityGrade
    calculation_details: dict[str, Any]
    provenance: dict[str, Any]


class ContinuousFindingResponse(BaseModel):
    """Public API representation of a proactive finding."""
    id: int
    business_id: str
    organization_id: str
    scan_run_id: int | None = None
    decision_id: int | None = None
    fingerprint: str
    metric_key: str
    entity_type: str
    entity_id: str
    entity_name: str | None = None
    change_type: str
    severity: FindingSeverity
    status: FindingStatus
    title: str
    summary: str
    current_value: float
    baseline_value: float
    delta_value: float
    relative_change_pct: float
    unit: str
    period_start: datetime
    period_end: datetime
    baseline_period_start: datetime | None = None
    baseline_period_end: datetime | None = None
    confidence_score: float
    business_impact_score: float
    urgency_score: float
    evidence_quality: EvidenceQualityGrade
    calculation_details: dict[str, Any]
    provenance_json: dict[str, Any]
    occurrence_count: int
    first_detected_at: datetime
    last_detected_at: datetime
    acknowledged_at: datetime | None = None
    acknowledged_by: str | None = None
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)


class ContinuousFindingListResponse(BaseModel):
    """Paginated or filtered list of continuous findings."""
    items: list[ContinuousFindingResponse]
    total_count: int
    active_count: int
    critical_count: int


class ContinuousScanRequest(BaseModel):
    """Parameters for running a proactive metric scan."""
    metrics: list[str] | None = None
    lookback_days: int = Field(default=30, ge=1, le=365)
    baseline_days: int = Field(default=30, ge=1, le=365)
    min_relative_change: float = Field(default=0.10, ge=0.01, le=10.0)
    anomaly_iqr_multiplier: float = Field(default=1.5, ge=1.0, le=5.0)
    cooldown_days: int = Field(default=7, ge=1, le=90, description="Days to suppress recurrence of recently resolved or dismissed findings")


class ContinuousScanResponse(BaseModel):
    """Summary result of a continuous scan execution."""
    scan_run_id: int
    business_id: str
    status: str
    trigger_type: str
    metrics_scanned: list[str]
    findings_detected_count: int
    findings_new_count: int
    findings_updated_count: int
    execution_time_ms: float


class FindingFeedbackRequest(BaseModel):
    """Payload to record human user feedback on a finding."""
    feedback_type: FeedbackType
    notes: str | None = None


class FindingFeedbackResponse(BaseModel):
    """Audit response for recorded user feedback."""
    id: int
    finding_id: int
    business_id: str
    organization_id: str
    user_id: str
    feedback_type: FeedbackType
    notes: str | None = None
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class FindingDecisionLinkRequest(BaseModel):
    """Request to link a finding to an authorized DecisionRecord (Phase 28)."""
    decision_id: int
    notes: str | None = None
